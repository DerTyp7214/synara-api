private fun exampleContext(id: String, slot: String?): UiContext =
    slotContext(slot).copy(params = EXAMPLE_PARAMS[id].orEmpty())

private fun slotContext(slot: String?): UiContext = when (slot) {
    UiSlots.ALBUM_DETAIL -> UiContext(UiEntityType.ALBUM, ENTITY_ID)
    UiSlots.ARTIST_DETAIL -> UiContext(UiEntityType.ARTIST, ENTITY_ID)
    UiSlots.SONG_DETAIL, UiSlots.SONG_MENU -> UiContext(UiEntityType.SONG, ENTITY_ID)
    UiSlots.PLAYLIST_DETAIL -> UiContext(UiEntityType.PLAYLIST, ENTITY_ID)
    UiSlots.COLLECTION_DETAIL -> UiContext(entityId = ENTITY_ID)
    else -> UiContext()
}

private fun encode(component: UiComponent): JsonElement =
    AppJson.encodeToJsonElement(UiComponent.serializer(), component)

private fun render(registered: RegisteredContribution, translations: TranslationService): Render {
    val contribution = registered.contribution
    val scope = ServerUiRenderScope(
        user = UserInfo.fromUser(ADMIN),
        context = exampleContext(contribution.id, contribution.slot),
        i18n = translations.translator(registered.source, TranslationService.DEFAULT_LOCALE),
        settings = InMemoryPluginSettings(),
        clientSchemaVersion = UiSchemaVersion.CURRENT,
        account = ADMIN,
        client = CLIENT,
        call = null,
    )
    return try {
        runBlocking {
            val tree = encode(contribution.render(scope))
            val toolbar = if (contribution.kind == UiContributionKind.PAGE) contribution.toolbar(scope) else emptyList()
            Render(tree, toolbar.map(::encode), null)
        }
    } catch (e: CancellationException) {
        throw e
    } catch (e: Exception) {
        Render(null, emptyList(), "${e::class.simpleName}: ${e.message}")
    }
}

private fun code(value: String) = "`$value`"

private fun StringBuilder.table(headers: List<String>, rows: List<List<String>>) {
    appendLine(headers.joinToString(" | ", prefix = "| ", postfix = " |"))
    appendLine(headers.joinToString("|", prefix = "|", postfix = "|") { "---" })
    rows.forEach { appendLine(it.joinToString(" | ", prefix = "| ", postfix = " |")) }
}

private fun slotIds(): List<String> =
    UiSlots::class.java.declaredFields
        .filter { Modifier.isStatic(it.modifiers) && it.type == String::class.java }
        .map { it.get(null) as String }

private fun builtInUiPlugins(): List<ISynaraPlugin> = PluginManager.builtInPlugins().filter { it is IUiPlugin }

private fun injectedTypes(plugin: Any): List<KClass<*>> =
    plugin::class.memberProperties
        .filter { it.javaField?.type == Lazy::class.java }
        .map { it.returnType.jvmErasure }

private fun registerPlugin(
    plugin: ISynaraPlugin,
    registry: UiRegistry,
    translations: TranslationService,
    renders: MutableMap<String, Render>,
) {
    if (plugin !is IUiPlugin) return
    val koin = startKoin {}.koin
    try {
        injectedTypes(plugin).forEach { type ->
            koin.declare<Any>(mockkClass(type, relaxed = true), secondaryTypes = listOf(type))
        }
        val context = mockk<PluginContext>(relaxed = true)
        every { context.i18n } returns translations.forSource(plugin.id)
        every { context.ui } returns registry.forSource(plugin.id)
        plugin.init(context)
        plugin.getUiContributions().forEach { context.ui.register(it) }
        registry.all().filter { it.source == plugin.id }.forEach { renders[it.contribution.id] = render(it, translations) }
    } finally {
        stopKoin()
    }
}

private fun declaringClass(type: Class<*>): Class<*> {
    var current = type
    while (true) {
        current = current.enclosingClass ?: return current
    }
}

private fun className(type: Class<*>): String {
    var current = type
    while (current.kotlin.qualifiedName == null) {
        current = current.enclosingClass ?: return type.name
    }
    return current.kotlin.qualifiedName ?: type.name
}

private fun sourceFile(type: Class<*>): String {
    val topLevel = declaringClass(type)
    val packageDir = File(SOURCE_ROOT, topLevel.packageName.replace('.', '/'))
    val direct = File(packageDir, "${topLevel.simpleName}.kt")
    if (direct.isFile) return direct.invariantSeparatorsPath
    val declaration = Regex("""\b(class|object|interface)\s+${Regex.escape(topLevel.simpleName)}\b""")
    val match = packageDir.listFiles { file -> file.isFile && file.extension == "kt" }
        ?.sortedBy { it.name }
        ?.firstOrNull { declaration.containsMatchIn(it.readText()) }
        ?: error("[UiContributionDocs] no source file declares ${topLevel.name} in ${packageDir.path}")
    return match.invariantSeparatorsPath
}

private fun buildCatalogue(): Catalogue {
    val registry = UiRegistry()
    val translations = TranslationService(registry)
    CoreUiContributions(
        registry = registry,
        translationService = translations,
        uiService = mockk(relaxed = true),
        importerState = mockk(relaxed = true),
        userService = mockk(relaxed = true),
        jobService = mockk(relaxed = true),
        coverGenerationService = mockk<CoverGenerationService>(relaxed = true) {
            coEvery { row(any()) } answers {
                CoverGenerationService.TargetRow(
                    target = firstArg(),
                    name = "Example",
                    creator = ADMIN.id,
                    imageId = UUID(0, 4),
                    imageSource = ImageSource.GENERATED,
                    coverStyle = null,
                    coverSeed = null,
                )
            }
        },
        hueService = mockk(relaxed = true),
        listenShareService = mockk(relaxed = true),
        credentialServerAdmin = mockk(relaxed = true) {
            coEvery { health() } returns CredentialServerHealth(true, CredentialProtocol.PROTOCOL_VERSION, "1.0.0")
            coEvery { listClients() } returns listOf(EXAMPLE_CLIENT)
            coEvery { getClient(EXAMPLE_CLIENT.id) } returns EXAMPLE_CLIENT
            coEvery { listCredentials() } returns listOf(EXAMPLE_CREDENTIAL)
            coEvery { getCredential(EXAMPLE_CREDENTIAL.name) } returns EXAMPLE_CREDENTIAL
        },
        credentialServerConnection = mockk<CredentialServerConnectionSource>(relaxed = true) {
            coEvery { current() } returns EXAMPLE_CONNECTION
        },
        credentialProvider = mockk(relaxed = true),
        remoteCredentials = mockk(relaxed = true),
        localCredentials = mockk(relaxed = true) {
            every { entry(EXAMPLE_LOCAL_CREDENTIAL) } returns exampleLocalEntry()
            coEvery { origin(EXAMPLE_LOCAL_CREDENTIAL) } returns CredentialOrigin.NONE
        },
        serverConfig = mockk(relaxed = true),
        pluginManager = mockk(relaxed = true),
    ).register()

    val plugins = builtInUiPlugins()
    val renders = mutableMapOf<String, Render>()
    plugins.forEach { registerPlugin(it, registry, translations, renders) }

    val entries = registry.all().map { registered ->
        val contribution = registered.contribution
        val translator = translations.translator(registered.source, TranslationService.DEFAULT_LOCALE)
        Entry(
            registered = registered,
            title = translator.t(contribution.titleKey),
            description = contribution.descriptionKey?.let { translator.t(it) },
            className = className(contribution.javaClass),
            file = sourceFile(contribution.javaClass),
            render = renders[contribution.id] ?: render(registered, translations),
        )
    }
    val declaredSlots = slotIds()
    val extraSlots = entries.mapNotNull { it.registered.contribution.slot }.distinct() - declaredSlots.toSet()
    val slots = (declaredSlots + extraSlots).map { slot ->
        slot to entries.filter { it.registered.contribution.slot == slot }.map { it.registered.contribution.id }
    }
    val sources = listOf(UiRegistry.SERVER_SOURCE to false, CREDENTIAL_SERVER_UI_SOURCE to false) +
        plugins.map { it.id to true }
    return Catalogue(slots, sources, entries)
}

private fun iconName(icon: UiIcon?): String? = when (icon) {
    null -> null
    is UiIcon.Named -> icon.name.name
    is UiIcon.Url -> icon.url
    is UiIcon.Image -> icon.imageId.toString()
}

private fun buildJson(catalogue: Catalogue): String {
    val json = Json { prettyPrint = true }
    val root = buildJsonObject {
        putJsonArray("slots") {
            catalogue.slots.forEach { (slot, ids) ->
                addJsonObject {
                    put("id", slot)
                    putJsonArray("contributions") { ids.forEach { add(it) } }
                }
            }
        }
        putJsonArray("sources") {
            catalogue.sources.forEach { (id, plugin) ->
                addJsonObject {
                    put("id", id)
                    put("plugin", plugin)
                }
            }
        }
        putJsonArray("contributions") {
            catalogue.entries.forEach { entry ->
                val contribution = entry.registered.contribution
                addJsonObject {
                    put("id", contribution.id)
                    put("kind", contribution.kind.name)
                    put("slot", contribution.slot)
                    put("source", entry.registered.source)
                    put("title", entry.title)
                    put("description", entry.description)
                    put("titleKey", contribution.titleKey)
                    put("descriptionKey", contribution.descriptionKey)
                    put("icon", iconName(contribution.icon))
                    put("order", contribution.order)
                    put("cardSize", contribution.cardSize.name.takeIf { contribution.kind == UiContributionKind.HOME_CARD })
                    putJsonArray("hooks") { contribution.hooks.map { it.name }.sorted().forEach { add(it) } }
                    putJsonObject("access") {
                        put("requiresAdmin", contribution.access.requiresAdmin)
                        putJsonArray("capabilities") {
                            contribution.access.capabilities.map { it.name }.sorted().forEach { add(it) }
                        }
                    }
                    put("className", entry.className)
                    put("file", entry.file)
                    putJsonObject("render") {
                        put("tree", entry.render.tree ?: JsonNull)
                        putJsonArray("toolbar") { entry.render.toolbar.forEach { add(it) } }
                        put("error", entry.render.error)
                    }
                }
            }
        }
    }
    return json.encodeToString(JsonObject.serializer(), root) + "\n"
}

private fun access(entry: Entry): String {
    val access = entry.registered.contribution.access
    val parts = listOfNotNull("admin".takeIf { access.requiresAdmin }) +
        access.capabilities.map { it.name }.sorted().map { code(it) }
    return parts.joinToString(", ").ifEmpty { "everyone" }
}

private fun buildMarkdown(catalogue: Catalogue, references: MarkdownDocReferences): String = buildString {
    appendLine(HEADLINE)
    appendLine()
    appendLine(GENERATED_BY)
    appendLine()
    appendLine(POINTERS)
    appendLine()
    appendLine(
        "Every server-driven UI contribution the server registers at startup, grouped by the source that registers it. " +
            "Kinds are entries of ${references.link("@UiContributionKind", "UiContributionDocs")}. " +
            "Titles are the English texts."
    )
    appendLine()
    appendLine(references.link(EXTERNAL_PLUGINS, "UiContributionDocs"))
    appendLine()

    appendLine("## Slots")
    appendLine()
    appendLine("The slot constants of `UiSlots` and the contributions shown in each, in render order.")
    appendLine()
    table(
        listOf("Slot", "Contributions"),
        catalogue.slots.map { (slot, ids) ->
            listOf(code(slot), ids.joinToString(", ") { code(it) }.ifEmpty { "-" })
        },
    )

    catalogue.sources.forEach { (source, plugin) ->
        appendLine()
        appendLine("## Source ${code(source)}")
        appendLine()
        if (plugin) {
            appendLine("Built-in plugin ${code(source)}. Its contributions are registered when the plugin is enabled.")
            appendLine()
        }
        val rows = catalogue.entries.filter { it.registered.source == source }
        if (rows.isEmpty()) {
            appendLine("No contributions.")
            return@forEach
        }
        table(
            listOf("Id", "Kind", "Slot", "Access", "Title", "File"),
            rows.map { entry ->
                val contribution = entry.registered.contribution
                listOf(
                    code(contribution.id),
                    code(contribution.kind.name),
                    contribution.slot?.let { code(it) } ?: "-",
                    access(entry),
                    entry.title.replace("|", "\\|"),
                    "[${entry.file.substringAfterLast('/')}](../${entry.file})",
                )
            },
        )
    }
}

private fun writeIfChanged(target: File, content: String) {
    if (target.exists() && target.readText() == content) {
        println("${target.path} is up to date.")
        return
    }
    target.parentFile?.mkdirs()
    target.writeText(content)
    println("Wrote ${target.path}")
}

fun main(args: Array<String>) {
    val markdownTarget = File(args.getOrNull(0) ?: "docs/SERVER_UI_CONTRIBUTIONS.md")
    val jsonTarget = File(args.getOrNull(1) ?: "docs/SERVER_UI_CONTRIBUTIONS.json")
    val modelsFile = File(args.getOrNull(2) ?: "docs/MODELS.md")
    val servicesFile = File(args.getOrNull(3) ?: "docs/RPC_SERVICES.md")
    val references = MarkdownDocReferences(
        services = parseDocEntries(servicesFile.readText()),
        models = parseDocEntries(modelsFile.readText()),
        serviceDoc = servicesFile.name,
        modelDoc = modelsFile.name,
    )
    val catalogue = buildCatalogue()
    writeIfChanged(markdownTarget, buildMarkdown(catalogue, references))
    writeIfChanged(jsonTarget, buildJson(catalogue))
}
